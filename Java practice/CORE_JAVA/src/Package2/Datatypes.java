package Package2;

public class Datatypes {
	static int patientID=22;// it is whole number.
	static byte age=35;//age is positive number and it rarely exceeds 120.
	static float weight=70.8f;//it allows decimal precision if its suffix is f.
	static char BloodGroup='A';//it stores single character in single quotes.
	static char Gender='F';//it has single character.
	static long ContactNumber=9876543298L;//it has large numbers
	static boolean IsInsured=true;//true or false status for insurance.
	static double Temperature=35.6666;//it allows decimals.
	
	
	public static void main(String [] args) {
		
	 System.out.println(patientID);
	 System.out.println(age);	
	 System.out.println(weight);	
	 System.out.println(BloodGroup);	
	 System.out.println(Gender);	
	 System.out.println(ContactNumber);	
	 System.out.println(IsInsured);	
	 System.out.println(Temperature);		
	}

}
