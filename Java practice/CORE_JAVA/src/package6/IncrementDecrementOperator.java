package package6;

public class IncrementDecrementOperator {

	public static void main(String[] args) {
		int a=5;
		
		System.out.println("Initial Value :" + a);
		System.out.println("Pre Increment Value :" +(++a));
		System.out.println("After Pre Increment Value :" + a);
		System.out.println("Pre Decrement Value :" + (--a));
		System.out.println("After Pre Decrement Value :" + a);
		System.out.println("Post Increment Value :" + (a++));
		System.out.println("After Post Increment Value :" + a);
		System.out.println("Post Decrement Value :" + (a--));
		System.out.println("After Post Decrement Value :" + a);

	}

}
