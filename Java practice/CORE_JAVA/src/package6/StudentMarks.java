package package6;

public class StudentMarks {

	public static void main(String[] args) {
		int Marks1 = 85;
		int Marks2 = 90;
		
		System.out.println("Student Marks1 < Student Marks2 :"+(Marks1 < Marks2));
		System.out.println("Student Marks1 > Student Marks2 :"+(Marks1 > Marks2));
		System.out.println("Student Marks1 <= Student Marks2 :"+(Marks1 <= Marks2));
		System.out.println("Student Marks1 == Student Marks2 :"+(Marks1 == Marks2));
		System.out.println("Student Marks1 != Student Marks2 :"+(Marks1 != Marks2));
     }

}
