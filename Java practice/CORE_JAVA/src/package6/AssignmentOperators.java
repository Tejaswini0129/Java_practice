package package6;

public class AssignmentOperators {
	
	public static void main (String [] args) {
		int a =100;
		System.out.println("Initial Value :"+a);
		 a+= 10;
		 System.out.println("After += :"+a);
		 a -= 10;
		 System.out.println("After -= :"+a);
		 a *= 10;
		 System.out.println("After *= :"+a);
		 a /= 10;
		 System.out.println("After /= :"+a);
		 a %= 10;
		 System.out.println("After %= :"+a);
	}

}
